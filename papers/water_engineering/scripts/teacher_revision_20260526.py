def append_blocks(chapter_title: str, section_title: str, blocks: list[dict[str, object]]) -> None:
    for chapter in chapters["chapters"]:
        if chapter["title"] == chapter_title:
            for sec in chapter["sections"]:
                if sec["title"] == section_title:
                    sec["blocks"].extend(blocks)
                    return
    raise KeyError((chapter_title, section_title))


