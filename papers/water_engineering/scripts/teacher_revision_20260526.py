def p(text: str) -> dict[str, str]:
    return {"type": "p", "text": text}


def formula(number: str, latex: str) -> dict[str, str]:
    return {"type": "formula", "number": number, "latex": latex}


def figure(path: str, caption: str, width: float = 5.8, page_break_before: bool = False) -> dict[str, object]:
    block: dict[str, object] = {
        "type": "figure",
        "path": path,
        "caption": caption,
        "width_in": width,
    }
    if page_break_before:
        block["page_break_before"] = True
    return block


def table(caption: str, headers: list[str], rows: list[list[object]], widths: list[float] | None = None) -> dict[str, object]:
    block: dict[str, object] = {
        "type": "table",
        "caption": caption,
        "headers": headers,
        "rows": rows,
    }
    if widths:
        block["widths_in"] = widths
    return block


def section(title: str, blocks: list[dict[str, object]], subsections: list[dict[str, object]] | None = None) -> dict[str, object]:
    data: dict[str, object] = {"title": title, "blocks": blocks}
    if subsections:
        data["subsections"] = subsections
    return data


