ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content"


def p(text: str) -> dict:
    return {"type": "p", "text": text}


def f(text: str, latex: str, number: str) -> dict:
    return {"type": "formula", "text": text, "latex": latex, "number": number}


def fig(path: str, caption: str, width: float = 5.75) -> dict:
    return {"type": "figure", "path": path, "caption": caption, "width_in": width}


def tab(caption: str, headers: list[str], rows: list[list[str]], widths: list[float] | None = None) -> dict:
    block = {"type": "table", "caption": caption, "headers": headers, "rows": rows}
    if widths:
        block["widths_in"] = widths
    return block


def sec(title: str, blocks: list[dict] | None = None, subsections: list[dict] | None = None) -> dict:
    out = {"title": title}
    if blocks:
        out["blocks"] = blocks
    if subsections:
        out["subsections"] = subsections
    return out


def ch(title: str, sections: list[dict]) -> dict:
    return {"title": title, "sections": sections}


