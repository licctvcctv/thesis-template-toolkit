def renumber_chapter_tables(chapters: dict, chapter_title_start: str, table_chapter_number: int) -> None:
    chapter = next(c for c in chapters["chapters"] if c["title"].startswith(chapter_title_start))
    counter = 1

    def renumber_node(node: dict) -> None:
        nonlocal counter
        for block in node.get("blocks", []):
            if block.get("type") == "table":
                caption = block.get("caption", "")
                title = caption.split(" ", 1)[1] if " " in caption else caption
                block["caption"] = f"表{table_chapter_number}-{counter} {title}"
                counter += 1
        for subsection in node.get("subsections", []):
            renumber_node(subsection)

    for section in chapter.get("sections", []):
        renumber_node(section)


def renumber_chapter_figures(chapters: dict, chapter_title_start: str, figure_chapter_number: int) -> None:
    chapter = next(c for c in chapters["chapters"] if c["title"].startswith(chapter_title_start))
    counter = 1

    def renumber_node(node: dict) -> None:
        nonlocal counter
        for block in node.get("blocks", []):
            if block.get("type") == "figure":
                caption = block.get("caption", "")
                title = caption.split(" ", 1)[1] if " " in caption else caption
                block["caption"] = f"图{figure_chapter_number}-{counter} {title}"
                counter += 1
        for subsection in node.get("subsections", []):
            renumber_node(subsection)

    for section in chapter.get("sections", []):
        renumber_node(section)


def rebuild_figures_json(chapters: dict) -> list[dict]:
    figures: list[dict] = []
    for chapter in chapters["chapters"]:
        for section in chapter.get("sections", []):
            stack = [section] + section.get("subsections", [])
            for node in stack:
                for block in node.get("blocks", []):
                    if block.get("type") == "figure":
                        figures.append(
                            {
                                "id": f"fig{len(figures)+1}",
                                "source_category": "cad_detail" if "images/cad_details/" in block["path"] else "user_provided",
                                "path": block["path"],
                                "caption": block["caption"],
                            }
                        )
    return figures


