def remove_repetitive_fillers(chapters: dict) -> None:
    bad_patterns = [
        "为了回应工作量不足的问题",
        "章节内容可以从原则描述转向工程判断",
        "按“尺度--材料--施工--复核”的顺序说明",
        "正文更多围绕港口工程本身展开",
        "若前期说明不足，运营期维修会缺少可追溯",
        "需要和相邻专业协调。例如",
        "图纸表达不清、施工接口冲突或预算漏项",
        "采用工程化表述：先说明控制对象",
        "不能只写结论。正文应说明",
        "重点放在设计文件能否被复核",
    ]

    def clean_node(node: dict) -> None:
        blocks = []
        seen: set[str] = set()
        for block in node.get("blocks", []):
            if block.get("type") == "p":
                text = block.get("text", "")
                if any(pattern in text for pattern in bad_patterns):
                    continue
                compact = "".join(text.split())
                if compact in seen:
                    continue
                seen.add(compact)
            blocks.append(block)
        if "blocks" in node:
            node["blocks"] = blocks
        for subsection in node.get("subsections", []):
            clean_node(subsection)

    for chapter in chapters["chapters"]:
        for section in chapter.get("sections", []):
            clean_node(section)


